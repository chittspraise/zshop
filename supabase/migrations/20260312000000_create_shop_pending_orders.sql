-- Table to track pending order notifications sent to shops for quick 1/2 replies
CREATE TABLE IF NOT EXISTS public.shop_pending_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_phone TEXT NOT NULL,
    order_slug TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending', -- 'pending', 'accepted', 'declined', 'missed'
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_shop_pending_orders_phone ON public.shop_pending_orders(shop_phone, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_shop_pending_orders_slug ON public.shop_pending_orders(order_slug);
